# The python list order above is: label, cavedog, oa, managed, existing, exePrompt, versionAllowed,
# versionNotAllowed, versionUnknown, noWine, downloading, exeNotAllowed, error  == KEYS order.
here = os.path.dirname(os.path.abspath(__file__))
for locale, values in TRANSLATIONS.items():
    assert len(values) == len(KEYS), locale
    path = os.path.join(here, 'messages_%s.properties' % locale)
    with open(path, 'rb') as f:
        data = f.read()
    if KEYS[0].encode('utf-8') + b' =' in data:
        continue  # idempotence guard
    lines = ['# install dialog engine section (Open Annihilation)']
    lines += ['%s = %s' % (k, v) for k, v in zip(KEYS, values)]
    out = ('\r\n'.join(lines) + '\r\n').encode('utf-8')
    if data and not data.endswith(b'\n'):
        out = b'\r\n' + out
    with open(path, 'ab') as f:
        f.write(out)
